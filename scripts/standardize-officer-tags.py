def main():
    with open('server/src/data/officers.json', 'r') as f:
        officers = json.load(f)

    updated = 0
    for o in officers:
        name = o['name']
        if name not in OFFICER_DATA:
            print(f'  WARNING: {name} (ID {o["id"]}) not in mapping, keeping existing tags')
            continue

        d = OFFICER_DATA[name]
        new_tags = []
        new_tags.extend(d['social'])
        new_tags.append(d['region'])
        new_tags.extend(d['job'][:3])
        new_tags.append(d['pol'])
        if 'spec' in d:
            new_tags.extend(d['spec'][:3])
        if d['region'] in ['凉州','并州','幽州','南中']:
            new_tags.append('边地')
        o['tags'] = new_tags
        updated += 1

    with open('server/src/data/officers.json', 'w') as f:
        json.dump(officers, f, ensure_ascii=False, indent=2)
    print(f'✅ Updated {updated}/{len(officers)} officers with correct tags')

    from collections import Counter
    all_tags = Counter()
    for o in officers:
        for t in o.get('tags', []):
            all_tags[t] += 1
    print(f'\n=== Tag distribution ===')
    for t, c in all_tags.most_common(30):
        print(f'  {t}: {c}')
    print(f'\nTotal unique: {len(all_tags)}')

if __name__ == '__main__':
    main()
